#ifndef MQTT_REASON_CODES_H
#define MQTT_REASON_CODES_H
#include <stdint.h>

/* MQTT 5.0 reason codes (OASIS MQTT Version 5.0).
 * Shared success / error values used across CONNECT, CONNACK, PUBLISH,
 * PUBACK, SUBSCRIBE, SUBACK, UNSUBSCRIBE, UNSUBACK, DISCONNECT. */

/* ---- Success / granted ---- */
#define MQTT_RC_SUCCESS 0x00
#define MQTT_RC_NORMAL_DISCONNECTION 0x00
#define MQTT_RC_GRANTED_QOS_0 0x00
#define MQTT_RC_GRANTED_QOS_1 0x01
#define MQTT_RC_GRANTED_QOS_2 0x02
#define MQTT_RC_DISCONNECT_WITH_WILL 0x04
#define MQTT_RC_NO_MATCHING_SUBSCRIBERS 0x10
#define MQTT_RC_NO_SUBSCRIPTION_EXISTED 0x11
#define MQTT_RC_CONTINUE_AUTHENTICATION 0x18
#define MQTT_RC_REAUTHENTICATE 0x19

/* ---- Errors (0x80+) ---- */
#define MQTT_RC_UNSPECIFIED_ERROR 0x80
#define MQTT_RC_MALFORMED_PACKET 0x81
#define MQTT_RC_PROTOCOL_ERROR 0x82
#define MQTT_RC_IMPLEMENTATION_SPECIFIC 0x83
#define MQTT_RC_UNSUPPORTED_PROTOCOL_VER 0x84
#define MQTT_RC_CLIENT_IDENTIFIER_NOT_VALID 0x85
#define MQTT_RC_BAD_USER_NAME_OR_PASSWORD 0x86
#define MQTT_RC_NOT_AUTHORIZED 0x87
#define MQTT_RC_SERVER_UNAVAILABLE 0x88
#define MQTT_RC_SERVER_BUSY 0x89
#define MQTT_RC_BANNED 0x8A
#define MQTT_RC_SERVER_SHUTTING_DOWN 0x8B
#define MQTT_RC_BAD_AUTHENTICATION_METHOD 0x8C
#define MQTT_RC_KEEP_ALIVE_TIMEOUT 0x8D
#define MQTT_RC_SESSION_TAKEN_OVER 0x8E
#define MQTT_RC_TOPIC_FILTER_INVALID 0x8F
#define MQTT_RC_TOPIC_NAME_INVALID 0x90
#define MQTT_RC_PACKET_IDENTIFIER_IN_USE 0x91
#define MQTT_RC_PACKET_IDENTIFIER_NOT_FOUND 0x92
#define MQTT_RC_RECEIVE_MAXIMUM_EXCEEDED 0x93
#define MQTT_RC_TOPIC_ALIAS_INVALID 0x94
#define MQTT_RC_PACKET_TOO_LARGE 0x95
#define MQTT_RC_MESSAGE_RATE_TOO_HIGH 0x96
#define MQTT_RC_QUOTA_EXCEEDED 0x97
#define MQTT_RC_ADMINISTRATIVE_ACTION 0x98
#define MQTT_RC_PAYLOAD_FORMAT_INVALID 0x99
#define MQTT_RC_RETAIN_NOT_SUPPORTED 0x9A
#define MQTT_RC_QOS_NOT_SUPPORTED 0x9B
#define MQTT_RC_USE_ANOTHER_SERVER 0x9C
#define MQTT_RC_SERVER_MOVED 0x9D
#define MQTT_RC_SHARED_SUBS_NOT_SUPPORTED 0x9E
#define MQTT_RC_CONNECTION_RATE_EXCEEDED 0x9F
#define MQTT_RC_MAXIMUM_CONNECT_TIME 0xA0
#define MQTT_RC_SUB_IDS_NOT_SUPPORTED 0xA1
#define MQTT_RC_WILDCARD_SUBS_NOT_SUPPORTED 0xA2

/* Human-readable name for a reason code (never NULL). */
const char *mqtt_reason_code_name(uint8_t code);

/* Print a labelled reason-code line to stdout, e.g.
 *   [CONNACK] reason code : 0x00 (Success)
 */
void mqtt_print_reason(const char *packet_label, uint8_t code);

#endif
