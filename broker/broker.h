#ifndef BROKER_H
#define BROKER_H

/*
 * Broker interface and shared broker-state definitions.
 *
 * This header contains:
 * - MQTT client state maintained by the broker
 * - Global broker state
 * - Function declarations used by the broker implementation
 */

#include <pthread.h>
#include <stdint.h>
#include "../common/mqtt_packet.h"

/* Maximum number of clients that can be tracked by the broker simultaneously. */
#define BROKER_MAX_CLIENTS 64

/*
 * Per-client state maintained by the broker.
 *
 * Each connected MQTT client gets one MQTTClient structure. The structure
 * contains the client's socket, MQTT connection state, publisher/subscriber
 * role, subscription information, pending acknowledgement information,
 * and the thread handling that client.
 */
typedef struct
{
    /*
     * Socket and connection state.
     *
     * socket_fd       : TCP socket associated with the client.
     * connected       : broker-side client slot is currently in use.
     * mqtt_connected  : MQTT CONNECT was successfully completed.
     */
    int socket_fd;
    int connected;
    int mqtt_connected;

    /*
     * Client role flags.
     *
     * is_subscriber : client has successfully subscribed to at least one
     *                 supported topic.
     * is_publisher  : client has been identified as a publisher.
     */
    int is_subscriber;
    int is_publisher;

    /*
     * Subscription state.
     *
     * subscription_active    : client currently has an active subscription.
     * subscription_attempted : client has attempted a SUBSCRIBE operation.
     */
    int subscription_active;
    int subscription_attempted;

    /*
     * Separate flags allow one client to subscribe to both sensor topics
     * without treating those subscriptions as two separate clients.
     */
    int subscribed_temperature;
    int subscribed_humidity;

    /* MQTT Client Identifier and most recently stored topic filter. */
    char client_id[128];
    char topic_filter[128];

    /* QoS level accepted for the client's subscription. */
    uint8_t subscription_qos;

    /*
     * Packet identifiers used by the broker.
     *
     * next_server_pid : next packet identifier generated by the broker.
     * pending_pid     : packet identifier currently awaiting acknowledgement.
     */
    uint16_t next_server_pid;
    uint16_t pending_pid;

    /*
     * Acknowledgement and thread-control state.
     *
     * pending_ack : an acknowledgement is currently expected.
     * stopping    : client thread has been requested to terminate.
     */
    int pending_ack;
    int stopping;

    /*
     * Condition variable used when a thread needs to wait for an MQTT
     * acknowledgement associated with this client.
     */
    pthread_cond_t ack_cond;

    /* Thread responsible for handling this client's MQTT communication. */
    pthread_t thread;

    /*
     * Indicates whether pthread_create() successfully started the
     * client thread. Used later by broker_cleanup_threads().
     */
    int thread_started;

} MQTTClient;

/*
 * Global broker state.
 *
 * This structure contains information shared between the listening thread,
 * client-handling threads, and dashboard.
 */
typedef struct
{
    /*
     * Broker execution state and listening socket.
     *
     * broker_running : indicates whether the broker is currently running.
     * listen_fd      : TCP listening socket used to accept new clients.
     */
    int broker_running;
    int listen_fd;

    /*
     * Live counters displayed on the dashboard.
     *
     * connected_clients:
     *     Number of clients that completed MQTT CONNECT.
     *
     * connected_subscribers:
     *     Number of connected clients classified as subscribers.
     *     A client is counted only once even if it subscribes to both
     *     temperature and humidity.
     *
     * connected_publishers:
     *     Number of connected clients classified as publishers.
     *
     * These counters are updated when clients connect, obtain a role,
     * or disconnect.
     */
    int connected_clients;
    int connected_subscribers;
    int connected_publishers;

    /*
     * Latest sensor values received by the broker.
     *
     * The corresponding *_received flags indicate whether the broker has
     * actually received a value. This distinguishes an actual zero reading
     * from a sensor value that has not been received yet.
     */
    float temperature;
    float humidity;
    int temperature_received;
    int humidity_received;

    /*
     * Protects shared broker state.
     *
     * Multiple client threads can modify counters, client states, and
     * sensor values simultaneously, so access to these shared fields
     * must be synchronized.
     */
    pthread_mutex_t mutex;

    /*
     * Fixed-size array containing the state of every possible client.
     * Each array element represents one broker client slot.
     */
    MQTTClient clients[BROKER_MAX_CLIENTS];

} BrokerState;

/*
 * Global broker state instance.
 *
 * Defined in broker_state.c and shared by the broker source files.
 */
extern BrokerState g_broker;

/*
 * Initialize the broker state and synchronization objects.
 *
 * This should be called once before the broker starts accepting clients.
 */
void broker_state_init(void);

/*
 * Reset per-run broker values before starting a fresh listening session.
 *
 * Counters and previously received sensor values are cleared while the
 * already-created dashboard frame remains in place.
 */
void broker_state_reset_for_start(void);

/*
 * Find an unused client slot.
 *
 * The caller must already hold g_broker.mutex when calling this function.
 *
 * Returns the index of a free slot, or -1 when all slots are occupied.
 */
int broker_find_free_client_locked(void);

/*
 * Mark a client as a subscriber and store its accepted subscription.
 *
 * The subscriber counter is increased only when this client becomes a
 * subscriber for the first time.
 */
void broker_state_mark_subscriber(MQTTClient *c, const char *t, uint8_t qos);

/*
 * Store a sensor value received by the broker.
 *
 * The topic determines whether the value is stored as temperature or
 * humidity, and the corresponding received flag is set.
 */
void broker_state_record_value(const char *t, float v);

/*
 * Remove a client from the broker's active state.
 *
 * Updates the relevant counters, clears the client's runtime flags,
 * and wakes threads waiting for an acknowledgement from that client.
 */
void broker_state_remove_client(MQTTClient *c);

/*
 * Request termination of all currently connected client threads.
 *
 * Client sockets are shut down so that threads blocked on socket
 * operations can wake up and terminate.
 */
void broker_stop_clients(void);

/*
 * Join all client threads that were successfully started.
 *
 * This prevents terminated pthread resources from being left behind
 * when the broker shuts down.
 */
void broker_cleanup_threads(void);

/*
 * Thread entry point for accepting new TCP client connections.
 *
 * The accept thread creates or assigns a client slot and starts a
 * dedicated client-handling thread for each accepted connection.
 */
void *broker_accept_thread(void *arg);

/*
 * Thread entry point for handling one connected MQTT client.
 *
 * The client thread receives MQTT packets, processes the corresponding
 * requests, sends responses, and handles the client's connection lifetime.
 */
void *broker_client_thread(void *arg);

/*
 * Draw the broker dashboard frame once and update live information
 * without repeatedly clearing and redrawing the entire terminal.
 */
void broker_display_dashboard(void);

/*
 * Restore the terminal's normal scrolling region and terminal state
 * before the broker process exits.
 */
void broker_dashboard_shutdown(void);

#endif